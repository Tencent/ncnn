"""Prepare the iOS wheel toolchain inside cibuildwheel's cross venv.

Desktop builds do not use this toolchain. The running executable is a macOS host
executable, but the cross venv's sysconfig describes the selected iOS Python
framework slice.
"""

import json
import os
from pathlib import Path
import subprocess
import sys
import sysconfig


def prepare(output):
    if sys.platform != "ios" or sys.version_info[:2] not in {(3, 13), (3, 14), (3, 15)}:
        raise RuntimeError("Run with cibuildwheel's CPython 3.13-3.15 iOS cross Python")
    multiarch = sys.implementation._multiarch
    if multiarch not in {
        "arm64-iphoneos", "arm64-iphonesimulator", "x86_64-iphonesimulator"
    }:
        raise RuntimeError("Unexpected iOS target: " + multiarch)
    arch, sdk = multiarch.rsplit("-", 1)
    prefix = Path(sys.base_prefix).resolve()
    expected_slice = "ios-arm64" if sdk == "iphoneos" else "ios-arm64_x86_64-simulator"
    if prefix.name != expected_slice or prefix.parent.name != "Python.xcframework":
        raise RuntimeError("Expected a target Python.xcframework slice: " + str(prefix))
    include = Path(sysconfig.get_path("include")).resolve()
    if not include.is_relative_to(prefix) or not (include / "Python.h").is_file():
        raise RuntimeError("Missing iOS target Python headers: " + str(include))
    suffix = sysconfig.get_config_var("EXT_SUFFIX")
    abi = "{}{}".format(*sys.version_info[:2])
    if suffix != ".cpython-{}-{}.so".format(abi, sdk):
        raise RuntimeError("Unexpected iOS extension suffix: " + str(suffix))
    deployment_target = os.environ.get("IPHONEOS_DEPLOYMENT_TARGET", "14.0")
    sdk_path = subprocess.check_output(
        ["xcrun", "--sdk", sdk, "--show-sdk-path"], text=True
    ).strip()
    values = {
        "CMAKE_SYSTEM_NAME": "iOS",
        "CMAKE_SYSTEM_VERSION": deployment_target,
        "CMAKE_OSX_SYSROOT": sdk_path,
        "CMAKE_OSX_ARCHITECTURES": arch,
        "CMAKE_SYSTEM_PROCESSOR": arch,
        "CMAKE_OSX_DEPLOYMENT_TARGET": deployment_target,
        "CMAKE_TRY_COMPILE_TARGET_TYPE": "STATIC_LIBRARY",
        "CMAKE_FIND_ROOT_PATH": str(prefix),
        "CMAKE_FIND_ROOT_PATH_MODE_PROGRAM": "NEVER",
        "CMAKE_FIND_ROOT_PATH_MODE_LIBRARY": "ONLY",
        "CMAKE_FIND_ROOT_PATH_MODE_INCLUDE": "ONLY",
        "CMAKE_FIND_ROOT_PATH_MODE_PACKAGE": "ONLY",
        "PYBIND11_USE_CROSSCOMPILING": "ON",
        "Python_ROOT_DIR": str(prefix),
        "Python_INCLUDE_DIR": str(include),
        "Python_FIND_IMPLEMENTATIONS": "CPython",
        "Python_FIND_FRAMEWORK": "NEVER",
        "Python_FIND_REGISTRY": "NEVER",
        "PYTHON_MODULE_EXTENSION": suffix,
        "PYTHON_MODULE_DEBUG_POSTFIX": "",
        "PYTHON_IS_DEBUG": "OFF",
    }
    # explicit native compiler paths avoid inheriting a host sdk through cc/cxx
    for language, compiler in (("C", "clang"), ("CXX", "clang++")):
        values["CMAKE_" + language + "_COMPILER"] = subprocess.check_output(
            ["xcrun", "--sdk", sdk, "--find", compiler], text=True
        ).strip()
    output = Path(output).resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "# generated by prepare_ios.py from the target cross-python sysconfig\n"
        + "".join(
            'set({} [=[{}]=] CACHE STRING "iOS wheel build" FORCE)\n'.format(key, value)
            for key, value in values.items()
        )
    )
    details = {"platform": sysconfig.get_platform(), "multiarch": multiarch, **values}
    print(json.dumps(details, indent=2))


if __name__ == "__main__":
    prepare(sys.argv[1])
