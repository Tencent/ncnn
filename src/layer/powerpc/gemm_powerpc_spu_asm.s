# full tile inner loop. the accumulators stay in registers for the whole
# k panel; spu-gcc spills them to local store, which is the whole cost.
#
# gemm_full(slot, kb, a_base, b_base, acc_base)
#   $3 slot (unused, the bases already select it)
#   $4 kb     $5 a_base     $6 b_base     $7 acc_base
#   $0 return address, $1 stack pointer. both are left alone.
#
# $80-$127 are callee-saved on the spu. the caller keeps the mfc tag-update
# mode in one of them across this call, so every one of them this routine
# touches is spilled around the body. $2-$79 are caller-saved and free.
#
# accumulator (r, lane, c) lives in $4 + ((r*4+lane)*4 + c), loaded from and
# stored back to acc_base so the panel carries across calls.
# lqd/stqd only take a signed 10-bit word offset, which stops at 512 bytes,
# so the spill cannot live at the far end of a stack frame. one static buffer
# is enough: a single spu thread runs this, and it never re-enters itself.
# $2 is caller-saved and not yet holding anything here, so it addresses it.
