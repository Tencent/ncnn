// Modifications: consolidate the 8x3VL load/FMA/store schedule into a single
// extended-asm statement with complete clobbers; use NCNN row strides and
// preinitialized output; remove C++17, BF16 and static CSR initialization.
// See the repository LICENSE.txt for the upstream license.

#ifndef NCNN_GEMM_TORQ_TILE_8X3VL_H
#define NCNN_GEMM_TORQ_TILE_8X3VL_H

// D += A * B for exactly 8 rows and 3 * vl columns. K must be positive;
// vl must be VLMAX(e32,m1). Strides are in floats. The caller owns C/bias
// broadcasting, alpha/beta, threading and all matrix tails.
__attribute__((noinline))
static void gemm_torq_tile_8x3vl(const float* a, const float* b, float* d,
                              size_t lda, size_t ldb, size_t ldd, int K, size_t vl)
{
    asm volatile(
        "vsetvli zero, %[vl], e32, m1, ta, ma\n"
        "mv t0, %[d]\n"
        "mv t1, t0\n"
        "vle32.v v8, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v9, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v10, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v11, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v12, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v13, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v14, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v15, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v16, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v17, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v18, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v19, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v20, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v21, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v22, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v23, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v24, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v25, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v26, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v27, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v28, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vle32.v v29, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v30, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v31, (t1)\n"
        "mv t0, %[a]\n"
        "flw ft0, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft1, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft2, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft3, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft4, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft5, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft6, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "flw ft7, 0(t0)\n"
        "mv t1, %[b]\n"
        "vle32.v v0, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v1, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vle32.v v2, (t1)\n"
        "addi %[a], %[a], 4\n"
        "add %[b], %[b], %[ldb]\n"
        "addi %[k], %[k], -1\n"
        "beqz %[k], 2f\n"
        "1:\n"
        "mv t1, %[b]\n"
        "vfmacc.vf v8, ft0, v0\n"
        "vfmacc.vf v11, ft1, v0\n"
        "vfmacc.vf v14, ft2, v0\n"
        "vfmacc.vf v17, ft3, v0\n"
        "vfmacc.vf v20, ft4, v0\n"
        "vfmacc.vf v23, ft5, v0\n"
        "vfmacc.vf v26, ft6, v0\n"
        "vfmacc.vf v29, ft7, v0\n"
        "vle32.v v0, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vfmacc.vf v9, ft0, v1\n"
        "vfmacc.vf v12, ft1, v1\n"
        "vfmacc.vf v15, ft2, v1\n"
        "vfmacc.vf v18, ft3, v1\n"
        "vfmacc.vf v21, ft4, v1\n"
        "vfmacc.vf v24, ft5, v1\n"
        "vfmacc.vf v27, ft6, v1\n"
        "vfmacc.vf v30, ft7, v1\n"
        "vle32.v v1, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "mv t0, %[a]\n"
        "vfmacc.vf v10, ft0, v2\n"
        "flw ft0, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v13, ft1, v2\n"
        "flw ft1, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v16, ft2, v2\n"
        "flw ft2, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v19, ft3, v2\n"
        "flw ft3, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v22, ft4, v2\n"
        "flw ft4, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v25, ft5, v2\n"
        "flw ft5, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v28, ft6, v2\n"
        "flw ft6, 0(t0)\n"
        "add t0, t0, %[lda]\n"
        "vfmacc.vf v31, ft7, v2\n"
        "flw ft7, 0(t0)\n"
        "vle32.v v2, (t1)\n"
        "addi %[a], %[a], 4\n"
        "add %[b], %[b], %[ldb]\n"
        "addi %[k], %[k], -1\n"
        "bnez %[k], 1b\n"
        "2:\n"
        "vfmacc.vf v8, ft0, v0\n"
        "vfmacc.vf v11, ft1, v0\n"
        "vfmacc.vf v14, ft2, v0\n"
        "vfmacc.vf v17, ft3, v0\n"
        "vfmacc.vf v20, ft4, v0\n"
        "vfmacc.vf v23, ft5, v0\n"
        "vfmacc.vf v26, ft6, v0\n"
        "vfmacc.vf v29, ft7, v0\n"
        "vfmacc.vf v9, ft0, v1\n"
        "vfmacc.vf v12, ft1, v1\n"
        "vfmacc.vf v15, ft2, v1\n"
        "vfmacc.vf v18, ft3, v1\n"
        "vfmacc.vf v21, ft4, v1\n"
        "vfmacc.vf v24, ft5, v1\n"
        "vfmacc.vf v27, ft6, v1\n"
        "vfmacc.vf v30, ft7, v1\n"
        "vfmacc.vf v10, ft0, v2\n"
        "vfmacc.vf v13, ft1, v2\n"
        "vfmacc.vf v16, ft2, v2\n"
        "vfmacc.vf v19, ft3, v2\n"
        "vfmacc.vf v22, ft4, v2\n"
        "vfmacc.vf v25, ft5, v2\n"
        "vfmacc.vf v28, ft6, v2\n"
        "vfmacc.vf v31, ft7, v2\n"
        "mv t0, %[d]\n"
        "mv t1, t0\n"
        "vse32.v v8, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v9, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v10, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v11, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v12, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v13, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v14, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v15, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v16, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v17, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v18, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v19, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v20, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v21, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v22, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v23, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v24, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v25, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v26, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v27, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v28, (t1)\n"
        "add t0, t0, %[ldd]\n"
        "mv t1, t0\n"
        "vse32.v v29, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v30, (t1)\n"
        "add t1, t1, %[vbytes]\n"
        "vse32.v v31, (t1)\n"
        : [a] "+&r"(a), [b] "+&r"(b), [k] "+&r"(K)
        : [d] "r"(d), [lda] "r"(lda * sizeof(float)),
          [ldb] "r"(ldb * sizeof(float)), [ldd] "r"(ldd * sizeof(float)),
          [vl] "r"(vl), [vbytes] "r"(vl * sizeof(float))
        : "t0", "t1", "ft0", "ft1", "ft2", "ft3", "ft4", "ft5", "ft6", "ft7",
          "v0", "v1", "v2", "v8", "v9", "v10", "v11", "v12", "v13", "v14",
          "v15", "v16", "v17", "v18", "v19", "v20", "v21", "v22", "v23",
          "v24", "v25", "v26", "v27", "v28", "v29", "v30", "v31", "memory");
}

#endif // NCNN_GEMM_TORQ_TILE_8X3VL_H
